export function translate(language, key, variables = {}) {
  const table = translations[language] || translations.en

  let value =
    table[key] ??
    translations.en[key] ??
    key

  for (const [name, replacement] of Object.entries(variables)) {
    value = value.replaceAll(`{${name}}`, String(replacement))
  }

  return value
}
